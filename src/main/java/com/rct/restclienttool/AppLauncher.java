package com.rct.restclienttool;

/**
* Application launcher class that serves as an entry point for the REST Client Tool.
* This class delegates to the main JavaFX application class.
*
 * @author REST Client Tool
* @version 1.0
* @since 1.0
*/
public class AppLauncher {
    /**
     * Main entry point for the application.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {
        RestClientApplication.main(args);
    }
}


